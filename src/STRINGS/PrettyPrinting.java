public class PrettyPrinting {
    public static void main(String[] args) {
        float a = 453.1271f;
        System.out.printf("formatted number is  %.2f",a);

        //gives float number till .mentioned place and also rounded it off . 

        //just as we do in C language . 
        System.out.printf("Pie  : %.3f",Math.PI);
        System.out.println();
        System.out.printf("Hello my name is %s and I am %s","Aryan","bewakoof");
    }

}
